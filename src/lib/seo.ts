/** Keywords that belong to one page, plus its cluster label terms. */
export function keywordsForPage(path: string): string[] {
  return KEYWORD_CLUSTERS.filter((cluster) => cluster.page === path).flatMap(
    (cluster) => cluster.terms
  );
}

/* ------------------------------------------------------------------ *
 * Structured data
 *
 * Deliberately absent: aggregateRating and review markup. The product has no
 * real ratings to report, and inventing them is both a Google spam violation
 * and the exact dishonesty the escrow model is meant to prevent.
 * ------------------------------------------------------------------ */

export type Schema = Record<string, unknown>;
export type Crumb = { name: string; path: string };

function stripSchema<T>(value: T): T {
  // Removes empty-string/undefined noise so we never emit meaningless keys.
  return JSON.parse(
    JSON.stringify(value, (_key, val) => (val === undefined || val === "" ? undefined : val))
  ) as T;
}

export function organizationSchema(): Schema {
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": `${SITE.url}/#organization`,
    name: SITE.name,
    url: SITE.url,
    description: SITE.shortDescription,
    email: SITE.email,
    logo: {
      "@type": "ImageObject",
      url: absoluteUrl("/favicon.ico"),
    },
    areaServed: {
      "@type": "Country",
      name: SITE.country,
    },
    contactPoint: [
      {
        "@type": "ContactPoint",
        contactType: "customer support",
        email: SITE.supportEmail,
        areaServed: SITE.countryCode,
        availableLanguage: ["en"],
      },
    ],
  });
}

