export function webPageSchema({
  name,
  description,
  path,
  primaryImage,
}: {
  name: string;
  description: string;
  path: string;
  primaryImage?: string;
}): Schema {
  const url = absoluteUrl(path);
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "WebPage",
    "@id": `${url}/#webpage`,
    url,
    name,
    description,
    inLanguage: SITE.lang,
    isPartOf: { "@id": `${SITE.url}/#website` },
    about: { "@id": `${SITE.url}/#app` },
    primaryImageOfPage: primaryImage,
  });
}

export function breadcrumbSchema(trail: Crumb[]): Schema {
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: trail.map((crumb, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.path),
    })),
  });
}

export function faqSchema(items: { q: string; a: string }[]): Schema | null {
  if (!items.length) return null;
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  });
}

export function itemListSchema({
  name,
  items,
}: {
  name: string;
  items: { name: string; path: string }[];
}): Schema {
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "ItemList",
    name,
    numberOfItems: items.length,
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      url: absoluteUrl(item.path),
    })),
  });
}

export function serviceSchema({
  name,
  description,
  path,
  serviceType,
}: {
  name: string;
  description: string;
  path: string;
  serviceType: string;
}): Schema {
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "Service",
    "@id": `${absoluteUrl(path)}/#service`,
    name,
    description,
    serviceType,
    url: absoluteUrl(path),
    provider: { "@id": `${SITE.url}/#organization` },
    areaServed: { "@type": "Country", name: SITE.country },
    availableChannel: {
      "@type": "ServiceChannel",
      serviceUrl: absoluteUrl(path),
      availableLanguage: { "@type": "Language", name: "English" },
    },
  });
}

export function definedTermSchema({
  term,
  definition,
  path,
}: {
  term: string;
  definition: string;
  path: string;
}): Schema {
  return stripSchema({
    "@context": "https://schema.org",
    "@type": "DefinedTerm",
    "@id": `${absoluteUrl(path)}/#term`,
    name: term,
    description: definition,
    inDefinedTermSet: {
      "@type": "DefinedTermSet",
      name: `${SITE.name} glossary`,
      url: absoluteUrl("/glossary"),
    },
    url: absoluteUrl(path),
  });
}
